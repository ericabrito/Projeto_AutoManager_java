    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
         int linha = tblConsultaCliente.getSelectedRow();
        if (linha == -1){
        JOptionPane.showMessageDialog(this,"Selecione um cliente para excluir!");
        return;
}
        int id = Integer.parseInt(tblConsultaCliente.getValueAt(linha, 0).toString());

        int resposta = JOptionPane.showConfirmDialog(this,
                                                    "Desejar realmente excluir o cliente do ID" + id + "?", 
                                                    "Confirmar Excluir", JOptionPane.YES_NO_CANCEL_OPTION,
                                                    JOptionPane.QUESTION_MESSAGE);
        if(resposta != JOptionPane.YES_OPTION) {
           return;
}
        String sql = "Delete from cliente WHERE id = ?";

        try(Connection conex = conexao.conectar();
                PreparedStatement stmt = conex.prepareStatement(sql)){

                stmt.setInt(1, id);

                int registros = stmt.executeUpdate();
                if (registros > 0){
                JOptionPane.showMessageDialog(this, "Cliente excluido com sucesso!");
                atualizarTabela();
        } else{
        JOptionPane.showMessageDialog(this, "Cliente não encontrado!");
        }
      }catch (SQLException erro){
        JOptionPane.showMessageDialog(this, "Erro ao excluir cleente: " + erro.getMessage());
}
    }//GEN-LAST:event_btnExcluirActionPerformed

