    private void btnLocalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLocalizarActionPerformed
        String pesquisa = txtPesquisar.getText().trim();
        String tipo_pesquisa = cmbPesquisarPor.getSelectedItem().toString();
        
        
        ///////////////////////////////////////////Conferindo as informaçoes///////////////////////////////////////////
         if (pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(
                        this,
                        "Digite o id, nome, cpf",
                        "Pesquisa Vazia",
                        JOptionPane.WARNING_MESSAGE);
            return;
        }
         
         DefaultTableModel modelo = (DefaultTableModel) tblConsultaCliente.getModel();
        
        modelo.setRowCount(0);
        
        
        
        String sql ="";
        
        ///////////////////////////////////Verificando Pesquisa/////////////////////////////////////////////////////
        
         if (tipo_pesquisa.equals("ID")) {
            sql = "SELECT * FROM cliente "
                  + "WHERE id = ?";
                  
        
        }
        
        else if (tipo_pesquisa.equals("Nome")) {
        
             sql = "SELECT * FROM cliente "
                   + "WHERE nome ILIKE ? "
                   + "ORDER BY nome";
                }
        
        else if (tipo_pesquisa.equals("CPF")){
        
             sql = "SELECT * FROM cliente "
                   + "WHERE cpf ILIKE ? ";
        }
        
        
            try (Connection conex = conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)) {

            if (tipo_pesquisa.equals("ID")) {
        stmt.setInt(1, Integer.parseInt(pesquisa));
        
        
            } else {
        stmt.setString(1, "%" + pesquisa + "%");
    }
            
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                        resultado.getInt("id"),
                        resultado.getString("nome"),
                        resultado.getString("cpf"),
                        resultado.getString("telefone"),
                        resultado.getString("email"),
                        resultado.getString("endereco"),
                        resultado.getBoolean("ativo")});
                }
            }
            if (modelo.getRowCount() == 0){
             JOptionPane.showMessageDialog(this,
                           "Nenhum Cliente encontrado para: " + pesquisa,
                           "Resultado da Pesquisa",
                           JOptionPane.INFORMATION_MESSAGE);
              }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                    "Erro ao localizar  :\n" + erro.getMessage(),
                    "Erro no banco de dados",
                     JOptionPane.ERROR_MESSAGE);
        }
         
                        
    }//GEN-LAST:event_btnLocalizarActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
         String pesquisa = txtPesquisar.getText().trim();
        String tipo_pesquisa = cmbPesquisarPor.getSelectedItem().toString();
        
         if (pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(
                        this,
                        "Digite o id, nome, cpf ou telefone.",
                        "Pesquisa Vazia",
                        JOptionPane.WARNING_MESSAGE);
            return;
        }
         
         DefaultTableModel modelo = (DefaultTableModel)tblConsultaCliente.getModel();
        
        modelo.setRowCount(0);
        
        
        
        String sql = "";
        
        Integer id = null;
        
        if (tipo_pesquisa.equals("Id")) {
        try {
            id = Integer.parseInt(pesquisa);
            
            sql = "SELECT * FROM cliente WHERE id = ? ORDER BY id";
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID deve ser numérico.");
            return;
        }
        
        if (tipo_pesquisa == ("Nome")) {
        
             sql = "SELECT * FROM cliente "
                   + "WHERE nome ILIKE ? "
                   + "ORDER BY nome";
                }
        
        else if (tipo_pesquisa == "CPF"){
        
             sql = "SELECT * FROM cliente "
                   + "WHERE cpf   ILIKE ?";
        }
        else if (tipo_pesquisa == "ID"){
                sql = "SELECT * FROM cliente"
                        + "WHERE telefone ?";
                }
        
        try (Connection conex = conexao.conectar();
                
              PreparedStatement stmt = conex.prepareStatement(sql)){
            stmt.setString(1,"%" + pesquisa + "%");
            
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                        resultado.getInt("id"),
                        resultado.getString("nome"),
                        resultado.getString("cpf"),
                        resultado.getString("telefone") });
                }
            }
            if (modelo.getRowCount() == 0){
             JOptionPane.showMessageDialog(this,
                           "Nenhum Cliente encontrado para: " + pesquisa,
                           "Resultado da Pesquisa",
                           JOptionPane.INFORMATION_MESSAGE);
              }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                    "Erro ao localizar  :\n" + erro.getMessage(),
                    "Erro no banco de dados",
                     JOptionPane.ERROR_MESSAGE);
        }
        } 
    }//GEN-LAST:event_btnAlterarActionPerformed

