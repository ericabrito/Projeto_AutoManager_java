    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
         if (txtNome.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Informe o nome do mecânico!");
        txtNome.requestFocus();
        return;
    }
        
        String sqlInsert = """
                    INSERT INTO mecanico
                    (nome, especialidade, telefone, data_admissao, observacao, ativo)
                    VALUES (?, ?, ?, ?, ?, ?)
                    """;

        
        LocalDate data_Admissao;
        
        try {
    DateTimeFormatter formato = DateTimeFormatter
            .ofPattern("dd/MM/uuuu")
            .withResolverStyle(ResolverStyle.STRICT);

    data_Admissao = LocalDate.parse(
            txtDtAdmissao.getText().trim(), formato
    );

} catch (DateTimeParseException erro) {
    JOptionPane.showMessageDialog(this, "Data inválida! Use DD/MM/AAAA");
    return;
}
try {
    Connection conex = conexao.conectar();
    PreparedStatement stmt = conex.prepareStatement(sqlInsert);
    
    String nome = txtNome.getText().trim().toUpperCase();
    String especialidade = txtEspecialidade.getText().trim().toUpperCase();
    String telefone = txtTelefone.getText().trim().toUpperCase();
    stmt.setDate(4,java.sql.Date.valueOf(data_Admissao) );
    String observacao = AreaObservacao.getText().trim().toUpperCase();
    boolean ativo = cbkAtivo.isSelected();

    stmt.setString(1, nome);
    stmt.setString(2, especialidade);
    stmt.setString(3, telefone);
    stmt.setDate(4, java.sql.Date.valueOf(data_Admissao));
    stmt.setString(5, observacao);
    stmt.setBoolean(6, ativo);
    
    int linhas = stmt.executeUpdate();
    if (linhas > 0) {
        JOptionPane.showMessageDialog(this, "Cadastro mecanico realizado com sucesso!");
        
        
        txtNome.setText("");
        txtEspecialidade.setText("");
        txtTelefone.setText("");
        txtDtAdmissao.setText("");
        AreaObservacao.setText("");
        cbkAtivo.setSelected(true);
        txtNome.requestFocus();
    }
} catch (SQLException erro) {
    JOptionPane.showMessageDialog(this, "Não foi possível cadastrar o mecânico! - Erro: " + erro.getMessage());
    
}
    }//GEN-LAST:event_btnCadastrarActionPerformed

