    private void btnAbrirOsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirOsActionPerformed
      if (txtIdVeiculo.getText().trim().isEmpty()
            || txtIdMecanico.getText().trim().isEmpty()
            || txtIdServico.getText().trim().isEmpty()
            || txtDtAbertura.getText().trim().isEmpty()
            || AreaDescProblema.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Preencha os campos obrigatórios!");
        return;
    }

    String sql = "INSERT INTO ordem_servico (veiculo_id, mecanico_id, servico_id, "
               + "data_abertura, data_conclusao, status, valor_cobrado, "
               + "descricao_problema, diagnostico, observacao) "
               + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

    try (Connection con = conexao.conectar();
         PreparedStatement stmt = con.prepareStatement(sql)) {

        DateTimeFormatter fmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");

        stmt.setInt(1, Integer.parseInt(txtIdVeiculo.getText().trim()));
        stmt.setInt(2, Integer.parseInt(txtIdMecanico.getText().trim()));
        stmt.setInt(3, Integer.parseInt(txtIdServico.getText().trim()));
        stmt.setDate(4, java.sql.Date.valueOf(LocalDate.parse(txtDtAbertura.getText().trim(), fmt)));

        // Data de conclusão (opcional)
        String conclusao = txtDtConclusao.getText().trim();
        if (conclusao.replace("/", "").trim().isEmpty()) {
            stmt.setNull(5, java.sql.Types.DATE);
        } else {
            stmt.setDate(5, java.sql.Date.valueOf(LocalDate.parse(conclusao, fmt)));
        }
        
        

        // Status (se vazio, usa "Aberta")
        String status = String.valueOf(cmbStatus.getSelectedItem());

        String status_banco = "";

        if (status.equals("Aberto")) {
            status_banco = "ABERTA";

        } else if (status.equals("Em andamento")) {
            status_banco = "EM_ANDAMENTO";

        } else if (status.equals("Concluído")) {
            status_banco = "CONCLUIDA";

        } else if (status.equals("Cancelado")) {
            status_banco = "CANCELADA";
        }

        stmt.setString(6, status_banco);
        
        // Valor cobrado (opcional)
        String valor = txtValorCobrado.getText().trim().replace(",", ".");
        if (valor.isEmpty()) {
            stmt.setNull(7, java.sql.Types.DECIMAL);
        } else {
            stmt.setBigDecimal(7, new BigDecimal(valor));
        }

        stmt.setString(8, AreaDescProblema.getText().trim());
        stmt.setString(9, AreaDiagnostico.getText().trim());
        stmt.setString(10, AreaObservacao.getText().trim());

        stmt.executeUpdate();

        JOptionPane.showMessageDialog(this, "Ordem de serviço aberta com sucesso!");
        limparCampos();

    } catch (DateTimeParseException erro) {
        JOptionPane.showMessageDialog(this, "Data inválida! Use o formato dd/MM/yyyy.");
    } catch (NumberFormatException erro) {
        JOptionPane.showMessageDialog(this, "ID ou valor cobrado inválido: " + erro.getMessage());
    } catch (SQLException erro) {
        JOptionPane.showMessageDialog(this, "Erro ao abrir OS: " + erro.getMessage());
    }
}

